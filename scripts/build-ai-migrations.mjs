#!/usr/bin/env node
// Bundles the AI database's SQL files into a TS module so the migrations runner
// (app/ai/api/admin/migrate) can apply them from a serverless function without touching the
// filesystem. Order: prisma-ai/init.sql as "0000_init", then prisma-ai/migrations/*.sql sorted.
// Run by `npm run build`; the output is committed so tsc works on a fresh clone too.
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const initPath = path.join(ROOT, "prisma-ai/init.sql");
const migDir = path.join(ROOT, "prisma-ai/migrations");
const out = path.join(ROOT, "ai/db/migrations.generated.ts");

const entries = [{ name: "0000_init", sql: fs.readFileSync(initPath, "utf8") }];
if (fs.existsSync(migDir)) {
  for (const f of fs.readdirSync(migDir).filter((f) => f.endsWith(".sql")).sort()) {
    entries.push({ name: f.replace(/\.sql$/, ""), sql: fs.readFileSync(path.join(migDir, f), "utf8") });
  }
}

const body = `// GENERATED by scripts/build-ai-migrations.mjs — do not edit. Source: prisma-ai/init.sql + prisma-ai/migrations/*.sql
export const AI_MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`✓ ai/db/migrations.generated.ts: ${entries.map((e) => e.name).join(", ")}`);
